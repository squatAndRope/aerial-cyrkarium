// polska odmiana: 1 studio, 2–4 studia, 5+ studiów (12–14 też „studiów”)
function plural(n, one, few, many) {
  if (n === 1) return one;
  const d = n % 10, h = n % 100;
  return d >= 2 && d <= 4 && (h < 12 || h > 14) ? few : many;
}
